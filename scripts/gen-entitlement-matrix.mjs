// Generates frontend/src/lib/license/entitlementMatrix.ts from the Go feature
// registry (internal/extensions/license/features*.go), so the UI's fallback
// matrix cannot drift from the backend catalog.
//
//   node scripts/gen-entitlement-matrix.mjs           write the file
//   node scripts/gen-entitlement-matrix.mjs --check   fail if it is out of date
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'frontend/src/lib/license/entitlementMatrix.ts');
const CHECK = process.argv.includes('--check');

function readRegistry() {
    const run = spawnSync('go', ['run', './cmd/gen-entitlement-matrix'], {
        cwd: ROOT,
        encoding: 'utf8',
    });
    if (run.status !== 0) {
        console.error(run.stderr || run.error?.message || 'go run failed');
        process.exit(1);
    }
    return JSON.parse(run.stdout);
}

// 'query.advanced.ai-assist' -> QUERY_ADVANCED_AI_ASSIST
const constName = id => id.toUpperCase().replace(/[^A-Z0-9]+/g, '_');

function render(features) {
    const seen = new Map();
    for (const f of features) {
        const name = constName(f.id);
        if (seen.has(name)) {
            console.error(`Features "${seen.get(name)}" and "${f.id}" both map to FEATURE.${name}`);
            process.exit(1);
        }
        seen.set(name, f.id);
    }

    const lines = [];
    lines.push('// GENERATED by scripts/gen-entitlement-matrix.mjs from the Go feature registry');
    lines.push('// (internal/extensions/license/features*.go). Do not edit by hand:');
    lines.push('// declare the feature in Go, then run `npm run gen:entitlements`.');
    lines.push('');
    lines.push('export interface EntitlementPolicy {');
    lines.push('    defaultEnabled: boolean;');
    lines.push('    requiresActiveLicense?: boolean;');
    lines.push('}');
    lines.push('');
    lines.push('export const FEATURE = {');
    for (const f of features) lines.push(`    ${constName(f.id)}: '${f.id}',`);
    lines.push('} as const;');
    lines.push('');
    lines.push('export type FeatureId = (typeof FEATURE)[keyof typeof FEATURE];');
    lines.push('');
    lines.push('export type EntitlementMatrix = Readonly<Record<FeatureId, EntitlementPolicy>>;');
    lines.push('');
    lines.push('// defaultEnabled is what the Free plan includes. Anything else needs an active');
    lines.push('// license, which is how the UI fails closed before the backend state arrives.');
    lines.push('export const ENTITLEMENT_MATRIX: EntitlementMatrix = {');
    for (const f of features) {
        const free = f.minTier === 'free';
        lines.push(
            free
                ? `    [FEATURE.${constName(f.id)}]: { defaultEnabled: true },`
                : `    [FEATURE.${constName(f.id)}]: { defaultEnabled: false, requiresActiveLicense: true },`,
        );
    }
    lines.push('};');
    return lines.join('\n') + '\n';
}

async function format(source) {
    const frontendRequire = createRequire(resolve(ROOT, 'frontend/package.json'));
    let prettier;
    try {
        prettier = frontendRequire('prettier');
    } catch {
        console.error('prettier is not installed: run `npm ci` in frontend/ first.');
        process.exit(1);
    }
    const config = (await prettier.resolveConfig(OUT)) ?? {};
    return prettier.format(source, { ...config, filepath: OUT });
}

const expected = await format(render(readRegistry()));

if (CHECK) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== expected) {
        console.error(
            'frontend/src/lib/license/entitlementMatrix.ts is out of date with the Go feature registry.\n' +
                'Run `npm run gen:entitlements` and commit the result.',
        );
        process.exit(1);
    }
    console.log('entitlementMatrix.ts matches the Go feature registry.');
} else {
    writeFileSync(OUT, expected, 'utf8');
    console.log(`Wrote ${OUT}`);
}
