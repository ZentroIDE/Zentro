import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

const repoRoot = process.cwd();
const workspaceRoot = path.join(repoRoot, "..");
const sourceRoot = path.join(workspaceRoot, ".claude", "skills");
const targetRoot = path.join(workspaceRoot, ".agents", "skills");

async function main() {
  const entries = await readdir(sourceRoot, { withFileTypes: true });
  const skillDirs = entries.filter((entry) => entry.isDirectory()).map((entry) => entry.name);

  await rm(targetRoot, { recursive: true, force: true });
  await mkdir(targetRoot, { recursive: true });

  for (const skillDir of skillDirs) {
    const sourceSkillPath = path.join(sourceRoot, skillDir, "SKILL.md");
    const sourceContent = await readFile(sourceSkillPath, "utf8");
    const frontmatter = extractFrontmatter(sourceContent, sourceSkillPath);

    const targetSkillDir = path.join(targetRoot, skillDir);
    const targetSkillPath = path.join(targetSkillDir, "SKILL.md");
    const canonicalSkillPath = toPosix(path.relative(targetSkillDir, sourceSkillPath));

    const wrapperContent = [
      frontmatter.trim(),
      "",
      "<!-- Generated by scripts/sync-agent-skills.mjs. Edit the canonical skill under .claude/skills/ instead. -->",
      "",
      `Canonical instructions live in \`${canonicalSkillPath}\`.`,
      `Read that file completely before acting, then follow any referenced files from the canonical skill directory.`,
      "Use this wrapper only to expose the same skill set to Codex via `.agents/skills`.",
      "",
    ].join("\n");

    await mkdir(targetSkillDir, { recursive: true });
    await writeFile(targetSkillPath, wrapperContent, "utf8");
  }

  console.log(`Synced ${skillDirs.length} Codex skill wrappers to ${path.relative(repoRoot, targetRoot)}`);
}

function extractFrontmatter(content, filePath) {
  const match = content.match(/^---\r?\n[\s\S]*?\r?\n---/);
  if (!match) {
    throw new Error(`Missing frontmatter in ${filePath}`);
  }

  return match[0];
}

function toPosix(value) {
  return value.split(path.sep).join("/");
}

await main();
