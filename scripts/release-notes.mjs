#!/usr/bin/env node
/**
 * release-notes.mjs — single source of truth for user-facing release notes.
 *
 * Source files:  release-notes/v<version>.md  (frontmatter + Markdown body)
 * Derived:       RELEASE_NOTES.md, release-notes/index.json, GitHub Release bodies.
 *
 * See release-notes/README.md for the contract.
 */
import {
  readFileSync,
  writeFileSync,
  readdirSync,
  existsSync,
} from 'node:fs';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const NOTES_DIR = join(root, 'release-notes');
const PKG_FILE = join(root, 'package.json');
const LEGACY_FILE = join(root, 'RELEASE_NOTES.md');
const INDEX_FILE = join(NOTES_DIR, 'index.json');

const STUB_MARK = '<!-- TODO: write the release notes for this version -->';
const GENERATED_HEADER =
  '<!-- GENERATED by scripts/release-notes.mjs from release-notes/v*.md — do not edit by hand. -->';

function fail(msg) {
  console.error(`release-notes: ${msg}`);
  process.exit(1);
}

function normalizeVersion(v) {
  return String(v || '').trim().replace(/^v/, '');
}

function parseNote(file) {
  const raw = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!m) fail(`${file}: missing "---" frontmatter block`);
  const fm = {};
  for (const line of m[1].split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const i = line.indexOf(':');
    if (i === -1) continue;
    fm[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  const body = raw.slice(m[0].length).trim();
  return { ...fm, body };
}

function splitVersion(v) {
  const [core, ...pre] = normalizeVersion(v).split('-');
  return { nums: core.split('.').map((n) => Number(n) || 0), pre: pre.join('-') };
}

/** Newest first. */
function compareVersionDesc(a, b) {
  const pa = splitVersion(a);
  const pb = splitVersion(b);
  for (let i = 0; i < 3; i++) {
    if ((pa.nums[i] || 0) !== (pb.nums[i] || 0)) return (pb.nums[i] || 0) - (pa.nums[i] || 0);
  }
  if (pa.pre && !pb.pre) return 1; // a is a pre-release of the same core -> sorts after b
  if (!pa.pre && pb.pre) return -1;
  return pb.pre.localeCompare(pa.pre);
}

function listNotes() {
  if (!existsSync(NOTES_DIR)) return [];
  return readdirSync(NOTES_DIR)
    .filter((f) => /^v.+\.md$/.test(f))
    .map((f) => {
      const file = join(NOTES_DIR, f);
      const note = parseNote(file);
      const version = normalizeVersion(note.version || f.replace(/^v/, '').replace(/\.md$/, ''));
      return {
        file,
        filename: f,
        version,
        tag: `v${version}`,
        date: note.date || null,
        channel: note.channel || (version.includes('-') ? 'beta' : 'stable'),
        prerelease: version.includes('-'),
        highlights: note.highlights || '',
        body: note.body,
      };
    })
    .sort((a, b) => compareVersionDesc(a.version, b.version));
}

function findNote(version) {
  const v = normalizeVersion(version);
  const direct = join(NOTES_DIR, `v${v}.md`);
  if (existsSync(direct)) {
    return listNotes().find((n) => n.file === direct) || null;
  }
  return listNotes().find((n) => n.version === v) || null;
}

function isStub(note) {
  if (!note) return true;
  if (!note.highlights.trim()) return true;
  if (note.body.includes(STUB_MARK)) return true;
  if (!/^###\s/m.test(note.body)) return true;
  const prose = note.body.replace(/^#.*$/gm, '').replace(/[-*\s]/g, '');
  return prose.length < 20;
}

function formatDate(d) {
  if (!d) return '';
  const dt = new Date(`${d}T00:00:00Z`);
  if (Number.isNaN(dt.getTime())) return d;
  return dt.toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    timeZone: 'UTC',
  });
}

function renderNote(note, { heading = false } = {}) {
  const parts = [];
  if (heading) {
    const date = formatDate(note.date);
    parts.push(`## ${note.tag}${date ? ` — ${date}` : ''}`);
  }
  if (note.highlights) parts.push(`**Highlights**: ${note.highlights}`);
  parts.push(note.body);
  return `${parts.join('\n\n')}\n`;
}

function pkgVersion() {
  return normalizeVersion(JSON.parse(readFileSync(PKG_FILE, 'utf8')).version);
}

// --- commands ---------------------------------------------------------------

function cmdRender(args) {
  const positional = args.find((a) => !a.startsWith('--'));
  const version = normalizeVersion(positional || pkgVersion());
  const note = findNote(version);
  if (!note) fail(`no release-notes/v${version}.md`);
  process.stdout.write(renderNote(note, { heading: args.includes('--heading') }));
}

function cmdBuildIndex() {
  const notes = listNotes();
  const index = notes.map((n) => ({
    version: n.version,
    tag: n.tag,
    date: n.date,
    channel: n.channel,
    prerelease: n.prerelease,
    highlights: n.highlights,
    body: n.body,
  }));
  writeFileSync(INDEX_FILE, `${JSON.stringify(index, null, 2)}\n`);
  console.log(`release-notes: wrote ${INDEX_FILE} (${index.length} entr${index.length === 1 ? 'y' : 'ies'})`);
}

function cmdSyncLegacy() {
  const [latest] = listNotes();
  const body = latest
    ? `# Zentro Release Notes (${latest.tag})\n\n${renderNote(latest)}`
    : '# Zentro Release Notes\n';
  writeFileSync(LEGACY_FILE, `${GENERATED_HEADER}\n\n${body}`);
  console.log(`release-notes: wrote ${LEGACY_FILE}${latest ? ` for ${latest.tag}` : ' (no source files)'}`);
}

function cmdCheck(args) {
  const i = args.indexOf('--version');
  const version = normalizeVersion(i !== -1 && args[i + 1] ? args[i + 1] : pkgVersion());
  const note = findNote(version);
  if (!note) fail(`missing release-notes/v${version}.md`);
  if (isStub(note)) fail(`release-notes/v${version}.md is still a stub — fill in "highlights" and the sections`);
  listNotes(); // parses every file; throws on malformed frontmatter
  console.log(`release-notes: OK for v${version}`);
}

function cmdNew(args) {
  const version = normalizeVersion(args.find((a) => !a.startsWith('--')));
  if (!version) fail('usage: release-notes.mjs new <version>');
  const file = join(NOTES_DIR, `v${version}.md`);
  if (existsSync(file)) {
    console.log(`release-notes: ${file} already exists`);
    return;
  }
  const today = new Date().toISOString().slice(0, 10);
  const template = `---
version: ${version}
date: ${today}
channel: ${version.includes('-') ? 'beta' : 'stable'}
highlights: ${STUB_MARK}
---

${STUB_MARK}

### New Features

-${' '}

### Fixes & Polish

-${' '}
`;
  writeFileSync(file, template);
  console.log(`release-notes: created ${file}`);
}

function cmdReleaseSync() {
  // Invoked by commit-and-tag-version's postbump hook: package.json is already bumped.
  const version = pkgVersion();
  const note = findNote(version);
  if (!note || isStub(note)) {
    fail(
      `release-notes/v${version}.md is missing or a stub.\n` +
        `        Write it before "npm run release" (scaffold: npm run release-notes -- new ${version}).`,
    );
  }
  cmdBuildIndex();
  cmdSyncLegacy();
  console.log('release-notes: synced RELEASE_NOTES.md + index.json');
}

const [cmd, ...args] = process.argv.slice(2);
switch (cmd) {
  case 'render':
    cmdRender(args);
    break;
  case 'build-index':
    cmdBuildIndex();
    break;
  case 'sync-legacy':
    cmdSyncLegacy();
    break;
  case 'check':
    cmdCheck(args);
    break;
  case 'new':
    cmdNew(args);
    break;
  case 'release-sync':
    cmdReleaseSync();
    break;
  default:
    console.log('usage: release-notes.mjs <render|build-index|sync-legacy|check|new|release-sync> [args]');
    process.exit(cmd ? 1 : 0);
}
